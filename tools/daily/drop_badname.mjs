/** 상품명 하나를 본다 → 걸리면 사유, 멀쩡하면 null */
export const badReason = (name) => {
  const s = String(name || '').trim();
  if (!s) return null;
  const hit = BAD.find(([re]) => re.test(s));
  if (hit) return hit[1];
  // 깨진 표기(따옴표·시각조각·머리번호·꺾쇠·꼬리기호)는 **버리지 않고 고친다**
  if (cleanJunkProbe(s)) return '군더더기';
  return null;
};
// badReason 안에서 쓰려고 미리 선언 — 실제 구현은 아래 cleanJunk
let cleanJunkProbe = () => null;

// ── 🔴🔴 2026-10-01 라이브 실측으로 가른 것 — **사유마다 다루는 법이 다르다**
//   라이브 2,611행에 걸어보니 걸린 10건 중 **대부분이 진짜 공구**였다:
//     「프로쉬 11월 정규 기획전」·「윙플라 CJ 기획전」·「정품 호주 UGG 26 신상 기획전」
//     「국내유일 무항생제 Non-gmo 새우」·「국내최초 ai카시트 버디」
//   브랜드가 앞에 있는 `기획전`·`할인전` 은 **모음전 형태의 정상 공구**다 — 내리면 매출이 사라진다.
//   등록 직전(승인표)에는 넓게 걸러도 다음 회차에 다시 들어오지만,
//   **이미 라이브에 있는 행을 내리는 건 되돌리기 전까지 손님이 못 본다.** 그래서 라이브는 좁게 본다.
/** 라이브에서 **내려야** 하는 사유 — 사람이 봐도 상품명이 아닌 것만 */
export const HARD = new Set(['문장형', '문장형2', '조사끝', '안내문구', '해시태그잔해', '구어체잔해', '숫자잔해', '공구아님']);
/** 라이브에서 **이름만 고치면 되는** 사유 — 상품은 멀쩡하고 군더더기가 붙은 것 */
export const FIXABLE = new Set(['가격붙음', '날짜붙음', '군더더기']);

// 🔴🔴 2026-10-01 사장님 지적 — 카드 2쪽 상품명이 깨져 있었다:
//   «"짐버 프리미엄 유기농 생강농축액"» · «00, [NEW] 바이리브 생기철철 콜라겐» · «00PM - 마사지베개»
//   «8.자동스퀴지:» · «플레인팟<매일 안심할 수 있는 이유>» · «욕실청소 종결템'스퀴지'»
//   → 아래 cleanJunk 가 걷어낸다. live_audit 이 매일 돌며 **이름만 고치고 살린다**(내리지 않는다).
//
// ⚠ 같은 날 내가 낸 사고: 머리 시각조각을 `^[0O]{1,2}…` 로 지웠더니 **「Only 90kcal…」의 O 를 먹어
//    「nly 90kcal…」** 가 됐고 「Oello 수제화」가 「ello 수제화」가 됐다(둘 다 되돌렸다).
//    → 알파벳 `O` 는 **시각 꼴일 때만** 지운다(`00PM`·`00시`·`00,`). 맨 앞 글자 하나를 그냥 깎지 않는다.
const JUNK = [
  [/^\s*0{2}\s*(?:PM|AM|pm|am|시)\s*[-–—,.:]?\s*/u, ''],      // 00PM - · 00시
  [/^\s*0{2}\s*[,.:]\s*/u, ''],                                // 00,  00:
  [/^\s*\d{1,2}\s*[.)]\s+/u, ''],                              // 「8. 자동스퀴지」 머리번호 (뒤에 공백이 있어야 — 「3.5kg」 보호)
  [/\[[^\]]{0,12}\]/gu, ' '],                                  // [NEW] [단독]
  [/\s*[<〈]\s*[^>〉]{4,}\s*[>〉]\s*/gu, ' '],                   // <매일 안심할 수 있는 이유>
  [/["'`‘’“”]/gu, ''],                                         // 따옴표 — 브랜드를 감쌌을 뿐이다
  // 🔴 판촉 머리말 — 상품명 앞에 붙은 자랑. 2026-10-01 사장님 "캡션읽고 다 고쳐놔" 뒤 넣었다.
  //    ⚠ `국내산`·`국산`·`유기농`·`무항생제` 는 **사실 표기**라 안 뗀다(상품명의 일부다).
  //       「무항생제 Non-GMO 새우」가 그 예다. 자랑 낱말만 좁게 본다.
  [/^\s*(최저가|초특가|역대급|국내최초|국내유일|세계최초|업계최초|단독최저가)\s+/u, ''],
  [/\s{2,}/gu, ' '],
  [/[\s:,.·~\-–—]+$/u, ''],                                    // 꼬리 기호
];
/** 군더더기를 걷어낸 이름 (바뀐 게 없으면 null) */
export const cleanJunk = (name) => {
  let s = String(name || '');
  for (const [re, to] of JUNK) s = s.replace(re, to);
  s = s.trim();
  if (!s || s === String(name || '').trim()) return null;
  if (s.replace(/\s/g, '').length < 2) return null;            // 다 깎여 나가면 고친 게 아니다
  return s;
};
cleanJunkProbe = cleanJunk;   // badReason 이 쓸 수 있게 연결 (위 선언 참조)
/** 꼬리 떼기 — 가격·날짜가 붙은 이름을 살린다 (못 떼면 null) */
export const stripTail = (name) => {
  let s = String(name || '').trim();
  s = s.replace(/\s*\d{1,3}(,\d{3})+\s*원.*$/u, '')          // 「… 6,230원 무료배송」
       .replace(/\s*\d{3,}\s*원\s*$/u, '')                    // 「… 가디건129000원」 은 붙어 있어 아래에서 다시 본다
       .replace(/(\D)\d{4,}\s*원\s*$/u, '$1')
       .replace(/\s*\d{1,2}\s*[./]\s*\d{1,2}\s*$/u, '')       // 「비트리 9.29」
       .replace(/\s*\d{1,2}\s*월\s*\d{1,2}\s*일?\s*$/u, '')
       .replace(/\s*(무료배송|무배)\s*$/u, '')
       .trim();
  // 떼고 나서도 상품명 꼴이어야 한다 — 2자 미만이거나 여전히 걸리면 못 고친 것이다
  if (s.replace(/\s/g, '').length < 2 || badReason(s)) return null;
  return s;
};

// ── 아래는 **직접 실행될 때만** 돈다 (import 하면 BAD·badReason 만 가져간다)
const isMain = !!process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1]);
if (isMain) {
  const f = process.argv[2];
  const hold = process.argv[3] && !process.argv[3].startsWith('--') ? process.argv[3] : null;
  const DRY = process.argv.includes('--dry');
  if (!f || !fs.existsSync(f)) { console.log('badname: -1'); console.error(`없는 파일: ${f}`); process.exit(2); }

  const lines = fs.readFileSync(f, 'utf8').split(/\r?\n/);

  // 🔴🔴 2026-10-01 실측 사고: 상품명 칸을 **고정 번호(cells[2])로 읽었다가 「셀러」 칸을 읽었다.**
  //    실제 순서는 `| # | 셀러 | 상품명 | 오픈 | 마감 | 대분류 | 소분류 | 핸들 |` 로 상품명은 3번이다.
  //    그래서 검사가 전부 통과하고 「스완핏 전송 '민스' 써주시면 디엠으로」가 라이브로 나갔다.
  //    → **헤더를 읽어 칸을 찾는다.** 메모리 `approval-table-header-trap` 이 그대로 적어둔 함정이다.
  //    헤더를 못 찾으면 **통과시키지 않는다**(badname: -1 → 호출처가 등록을 멈춘다).
  let NAME_COL = -1;
  for (const l of lines) {
    if (!/^\|/.test(l) || !/상품명/.test(l)) continue;
    const cells = l.split('|').map((x) => x.trim());
    NAME_COL = cells.findIndex((c) => c === '상품명' || c === '상품');
    if (NAME_COL > 0) break;
  }
  if (NAME_COL < 0) {
    console.log('badname: -1');
    console.error(`헤더에서 「상품명」 칸을 못 찾았다: ${f} — 칸 번호를 추측하지 않는다`);
    process.exit(3);
  }

  const keep = [], dropped = [];
  for (const l of lines) {
    if (!/^\|\s*\d+\s*\|/.test(l)) { keep.push(l); continue; }   // 헤더·구분선·주석은 그대로
    const cells = l.split('|').map((x) => x.trim());
    const why = badReason(cells[NAME_COL]);
    if (why) dropped.push([why, cells[NAME_COL], l]);
    else keep.push(l);
  }

  console.log(`badname: ${dropped.length}`);
  for (const [why, name] of dropped.slice(0, 30)) console.log(`   ${why}\t${name}`);
  if (dropped.length > 30) console.log(`   … 그 외 ${dropped.length - 30}행`);

  if (!DRY && dropped.length) {
    fs.writeFileSync(f, keep.join('\n'), 'utf8');
    if (hold) {
      const ts = new Date(Date.now() + 9 * 3600e3).toISOString().slice(0, 16).replace('T', ' ');
      fs.appendFileSync(hold, dropped.map(([why, , l]) => `| 상품명아님(${why}) ${ts} ${l.replace(/^\|/, '')}`).join('\n') + '\n', 'utf8');
    }
  }
}
