-- 브랜드 세일 일정 표 (2026-10-12, 사장님 "인스타 '10~12월 브랜드별 세일 일정' 같은 걸 우리 캘린더로 보게")
--
-- 무엇
--   올리브영 올영데이·무신사 블프·유니클로 감사제처럼 **브랜드가 정해 놓은 세일 기간**을 공구 캘린더 위에 함께 보여준다.
--   공구(gonggu)와는 성격이 다르다 — 셀러·결제링크·찜이 없고 "언제부터 언제까지" 가 전부다. 그래서 표를 따로 둔다.
--
-- 손님 화면(test.html → index.html)
--   anon 이 active=true 인 것만 읽는다. 종료일이 지난 건 화면에서 거른다(표에선 지우지 않는다 — 내년 같은 시기 참고용).
--   표가 없거나(아직 이 파일을 안 돌렸거나) 비어 있으면 화면은 /brand-sales.json 기본값으로 그린다.
-- 관리자(admin.html 🏷️ 브랜드세일 탭)
--   is_app_admin / is_app_staff 만 넣고 고치고 지운다. (핫딜·체험단과 같은 범위)
--
-- 적용:  supabase db query --file supabase/sql/brand_sales_86.sql --linked
-- 되돌리기:  drop table public.brand_sales;

create table if not exists public.brand_sales (
  id          bigint generated by default as identity primary key,
  brand       text not null,                         -- 화면에 보이는 브랜드명 (올리브영)
  brand_key   text,                                  -- 색·묶음용 영문 키 (oliveyoung). 비우면 brand 로 대신한다
  title       text not null,                         -- 세일명 (올리브영 올영데이)
  start_date  date not null,
  end_date    date,                                  -- null = 종료일 미정 ("10/06~" 처럼 브랜드가 안 밝힌 것)
  link        text,                                  -- 세일 페이지(없으면 브랜드 메인)
  major       text,                                  -- 대분류 (뷰티·패션…) — 캘린더 카테고리 칩과 맞춘다
  note        text,                                  -- 관리자 메모 (출처 등)
  active      boolean not null default true,         -- false = 화면에서 뺀다 (지우지 않고 감추기)
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists brand_sales_period_idx on public.brand_sales (start_date, end_date) where active;

-- updated_at 자동 갱신
create or replace function public.brand_sales_touch()
returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists brand_sales_touch on public.brand_sales;
create trigger brand_sales_touch before update on public.brand_sales
  for each row execute function public.brand_sales_touch();

-- 권한: security_lockdown_66 이후 새 표는 기본 권한이 없다 → 명시적으로 준다
alter table public.brand_sales enable row level security;
revoke all on table public.brand_sales from anon, authenticated;
grant select on table public.brand_sales to anon, authenticated;
grant insert, update, delete on table public.brand_sales to authenticated;
grant usage, select on sequence public.brand_sales_id_seq to authenticated;

drop policy if exists brand_sales_public_read on public.brand_sales;
create policy brand_sales_public_read on public.brand_sales
  for select to anon, authenticated
  using (active = true);

drop policy if exists brand_sales_admin_all on public.brand_sales;
create policy brand_sales_admin_all on public.brand_sales
  for all to authenticated
  using      (public.is_app_admin() or public.is_app_staff())
  with check (public.is_app_admin() or public.is_app_staff());

